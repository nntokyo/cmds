import Foundation

/// Claude in Chrome's native host (the Chrome extension's link to Claude Code), seen from cmds's accounts.
///
/// Claude Code registers `com.anthropic.claude_code_browser_extension.json` in each Chromium browser's
/// `NativeMessagingHosts` folder; its `path` is a wrapper script in the config directory of the account that last
/// turned Claude in Chrome on: `<CLAUDE_CONFIG_DIR>/chrome/chrome-native-host`. The manifest is one per browser for
/// every account, so when that config directory is removed or made again (signing in afresh, moving accounts around)
/// the browser starts a script that is not there and the extension cannot connect, under every account. `check`
/// finds such a manifest; `repair` puts the script back (never overwriting anything, never touching the manifest).
public enum ClaudeChromeHost {
    public static let manifestName = "com.anthropic.claude_code_browser_extension.json"
    /// The script Claude Code writes, relative to a config directory.
    public static let scriptSuffix = "/chrome/chrome-native-host"

    /// The browsers' folders under `~/Library/Application Support` that Claude Code installs the manifest in.
    static let browserFolders = [
        "Google/Chrome", "BraveSoftware/Brave-Browser", "Arc/User Data", "Chromium", "Microsoft Edge", "Vivaldi",
        "com.operasoftware.Opera",
    ]

    /// A manifest whose host script cannot be started.
    public struct Broken: Equatable, Sendable {
        /// The manifest file.
        public var manifest: String
        /// Its `path`: the script that is missing (or not executable).
        public var host: String
        /// The script is Claude Code's wrapper in a config directory (`…/chrome/chrome-native-host`), so `repair` can
        /// write it again. Otherwise it is left to the user.
        public var repairable: Bool

        public init(manifest: String, host: String, repairable: Bool) {
            self.manifest = manifest
            self.host = host
            self.repairable = repairable
        }
    }

    public struct RepairError: Error, CustomStringConvertible {
        public var description: String
        init(_ description: String) { self.description = description }
    }

    public static func manifestPaths(home: String = NSHomeDirectory()) -> [String] {
        browserFolders.map { "\(home)/Library/Application Support/\($0)/NativeMessagingHosts/\(manifestName)" }
    }

    /// The manifests whose host script is missing or not executable. A browser without the manifest (Claude in
    /// Chrome never turned on there) or with a manifest that cannot be read is not a problem.
    public static func check(home: String = NSHomeDirectory(), fileManager: FileManager = .default) -> [Broken] {
        var broken: [Broken] = []
        for manifest in manifestPaths(home: home) {
            guard let data = fileManager.contents(atPath: manifest), let host = hostPath(manifest: data),
                  !fileManager.isExecutableFile(atPath: host) else { continue }
            broken.append(Broken(manifest: manifest, host: host, repairable: isWrapperPath(host)))
        }
        return broken
    }

    /// The manifest's `path` (absolute); nil when it is not a manifest.
    static func hostPath(manifest: Data) -> String? {
        guard let object = try? JSONSerialization.jsonObject(with: manifest) as? [String: Any],
              let path = object["path"] as? String, path.hasPrefix("/") else { return nil }
        return path
    }

    static func isWrapperPath(_ path: String) -> Bool {
        path.hasSuffix(scriptSuffix) && path.count > scriptSuffix.count
    }

    /// The wrapper's text, as Claude Code writes it: `exec <claude> --chrome-native-host`.
    public static func wrapper(claude: String) -> String {
        "#!/bin/sh\n# Chrome native host wrapper script\n# Generated by Claude Code - do not edit manually\n"
            + "exec \(shellQuoted(claude)) --chrome-native-host\n"
    }

    static func shellQuoted(_ value: String) -> String {
        let plain = value.allSatisfy { $0.isLetter || $0.isNumber || "/._-+@:".contains($0) }
        return plain ? value : "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    /// The text for a missing wrapper: an existing wrapper of another config directory (the same text Claude Code
    /// wrote there), else one that runs the first `claude` found.
    static func wrapperText(configDirs: [String], claudeCandidates: [String], fileManager: FileManager) -> String? {
        for dir in configDirs {
            let path = dir + scriptSuffix
            guard fileManager.isExecutableFile(atPath: path),
                  let size = (try? fileManager.attributesOfItem(atPath: path))?[.size] as? Int, size <= 4096,
                  let data = fileManager.contents(atPath: path), let text = String(data: data, encoding: .utf8),
                  text.hasPrefix("#!"), text.contains("--chrome-native-host") else { continue }
            return text
        }
        return claudeCandidates.first { fileManager.isExecutableFile(atPath: $0) }.map(wrapper(claude:))
    }

    /// Where `claude` usually is: the native installer, Homebrew, npm's global folder.
    public static func claudeCandidates(home: String = NSHomeDirectory()) -> [String] {
        ["\(home)/.local/bin/claude", "\(home)/.claude/local/claude", "/opt/homebrew/bin/claude", "/usr/local/bin/claude"]
    }

    /// Writes the missing wrapper scripts of `broken` (repairable ones only; the folder is created when missing).
    /// `configDirs`: the accounts' config directories (and `~/.claude`), where a working wrapper is looked for first.
    /// Returns the scripts written. Never overwrites: a script that appeared meanwhile is left alone.
    @discardableResult
    public static func repair(_ broken: [Broken], configDirs: [String], home: String = NSHomeDirectory(),
                              fileManager: FileManager = .default) throws -> [String] {
        let hosts = broken.filter(\.repairable).map(\.host).reduce(into: [String]()) { if !$0.contains($1) { $0.append($1) } }
        guard !hosts.isEmpty else { return [] }
        guard let text = wrapperText(configDirs: configDirs, claudeCandidates: claudeCandidates(home: home),
                                     fileManager: fileManager) else {
            throw RepairError("claude was not found (looked in \(claudeCandidates(home: home).joined(separator: ", "))); "
                              + "start claude with --chrome once to let it write the script")
        }
        var written: [String] = []
        for host in hosts where !fileManager.fileExists(atPath: host) {
            try fileManager.createDirectory(atPath: (host as NSString).deletingLastPathComponent,
                                            withIntermediateDirectories: true)
            guard fileManager.createFile(atPath: host, contents: Data(text.utf8), attributes: [.posixPermissions: 0o755]) else {
                throw RepairError("could not write \(host)")
            }
            written.append(host)
        }
        // A script that is there but not executable: only its mode is fixed (its text is the user's or Claude Code's).
        for host in hosts where !written.contains(host) && fileManager.fileExists(atPath: host)
            && !fileManager.isExecutableFile(atPath: host) {
            try fileManager.setAttributes([.posixPermissions: 0o755], ofItemAtPath: host)
            written.append(host)
        }
        return written
    }
}
